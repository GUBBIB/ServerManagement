CREATE TABLE TB_USER_MANAGE
(
    `USER_ID`    BIGINT       NOT NULL AUTO_INCREMENT COMMENT 'Auto Increment\n유저 아이디 PK',
    `EMAIL`      VARCHAR(255) NOT NULL COMMENT '이메일',
    `PASSWORD`   VARCHAR(255) NOT NULL COMMENT '비밀번호',
    `NAME`       VARCHAR(45)  NOT NULL COMMENT '이름',
    `PHONE`      VARCHAR(11)  NOT NULL COMMENT '휴대폰번호 (010######## 형식, 11자리)',
    `ROLE`       VARCHAR(20)  NOT NULL DEFAULT 'USER' COMMENT '권한',
    `STATUS`     VARCHAR(20)  NOT NULL DEFAULT 'PENDING' COMMENT '상태\n[ PENDING = 대기, ACTIVE = 활성화, INACTIVE = 비활성화, SUSPENDED = 정지, WITHDRAWN = 탈퇴 ]',
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '[감사컬럼]\n생성일',
    `CREATED_BY` BIGINT NULL COMMENT '[감사컬럼]\n생성자',
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '[감사컬럼]\n수정일',
    `UPDATED_BY` BIGINT NULL COMMENT '[감사컬럼]\n수정자',
    `DELETED_AT` DATETIME(6) NULL COMMENT '[감사컬럼]\n삭제일',
    PRIMARY KEY (`USER_ID`),
    UNIQUE INDEX `EMAIL_UNIQUE` (`EMAIL` ASC) VISIBLE
) ENGINE = InnoDB
DEFAULT CHARACTER SET = utf8mb4
COLLATE = utf8mb4_0900_ai_ci
COMMENT = '유저 관리 테이블';
