CREATE TABLE TB_USER_ROLE_MANAGE
(
    `USER_ID`    BIGINT      NOT NULL COMMENT '역할을 부여받은 회원 ID',
    `ROLE_CODE`  VARCHAR(50) NOT NULL COMMENT '역할 코드',
    `CREATED_BY` BIGINT NULL COMMENT '[감사컬럼]\n역할 부여자',

    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '[감사컬럼]\n역할 부여일',
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '[감사컬럼]\n역할 수정일',
    `UPDATED_BY` BIGINT NULL COMMENT '[감사컬럼]\n역할 수정자',
    `DELETED_AT` DATETIME(6) NULL COMMENT '[감사컬럼]\n역할 삭제일',

    PRIMARY KEY (`USER_ID`, `ROLE_CODE`),

    INDEX        IDX_USER_ROLE_CODE (ROLE_CODE),
    INDEX        IDX_USER_ROLE_CREATED_BY (CREATED_BY),

    CONSTRAINT FK_USER_ROLE_USER
        FOREIGN KEY (USER_ID)
            REFERENCES TB_USER_MANAGE (USER_ID),

    CONSTRAINT FK_USER_ROLE_ROLE
        FOREIGN KEY (ROLE_CODE)
            REFERENCES TB_ROLE_MANAGE (ROLE_CODE),

    CONSTRAINT FK_USER_ROLE_CREATED_BY
        FOREIGN KEY (CREATED_BY)
            REFERENCES TB_USER_MANAGE (USER_ID)

) ENGINE = InnoDB
DEFAULT CHARACTER SET = utf8mb4
COLLATE = utf8mb4_0900_ai_ci
COMMENT = '회원별 역할 부여 관리 테이블';

